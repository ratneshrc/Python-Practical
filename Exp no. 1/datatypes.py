# Integer (int)
age = 20
print(age)

# Float
height = 175
print(height)

# String (str)
name = "Siddhesh"
print(name)

# Boolean (bool)
student = True
print(student)

# List
fruits = ["apple", "banana", "mango"]
print(fruits)

# Tuple
colors = ("red", "green", "blue")
print(colors)

# Set
rollnum = {11, 22, 33}
print(rollnum)

# NoneType
result = None
print(result)
